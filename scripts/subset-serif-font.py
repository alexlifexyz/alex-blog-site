#!/usr/bin/env python3
"""
Build a small Noto Serif SC subset that covers every character the built site renders in the serif face.

Why: headings are spread across many unicode-range slices of the full font (about 400 KB per page).
A subset of only the characters in use is a single small file. Characters added later still render,
because the sliced full font stays in the font stack as a fallback.

Usage (run after `npm run build`, whenever headings change):
  pip install fonttools brotli playwright
  python3 scripts/subset-serif-font.py /path/to/NotoSerifSC-SemiBold.otf

The source font is the SemiBold OTF from https://github.com/notofonts/noto-cjk (Serif/SubsetOTF/SC).
Writes public/fonts/noto-serif-sc-subset.woff2 and src/styles/fonts-subset.css.
"""
import functools
import http.server
import os
import socketserver
import sys
import threading

from fontTools import subset
from playwright.sync_api import sync_playwright

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIST = os.path.join(ROOT, "dist")
OUT_FONT = os.path.join(ROOT, "public", "fonts", "noto-serif-sc-subset.woff2")
OUT_CSS = os.path.join(ROOT, "src", "styles", "fonts-subset.css")
# Always include basic Latin, digits and common CJK punctuation so small copy edits keep working.
BASE = "".join(chr(c) for c in range(0x20, 0x7F)) + "，。、：；！？（）《》“”‘’—…·"


def pages():
    for dirpath, _, files in os.walk(DIST):
        for f in files:
            if f.endswith(".html"):
                rel = os.path.relpath(os.path.join(dirpath, f), DIST)
                yield "/" + rel.replace(os.sep, "/")


def collect_serif_text():
    class Quiet(http.server.SimpleHTTPRequestHandler):
        def log_message(self, *args):
            pass

    srv = socketserver.TCPServer(("127.0.0.1", 0), functools.partial(Quiet, directory=DIST))
    port = srv.server_address[1]
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    chars = set(BASE)
    js = """() => {
      const out = [];
      for (const el of document.querySelectorAll('body *')) {
        const ff = getComputedStyle(el).fontFamily;
        if (!ff.includes('Noto Serif SC')) continue;
        for (const n of el.childNodes) if (n.nodeType === 3) out.push(n.textContent);
      }
      return out.join('');
    }"""
    with sync_playwright() as p:
        browser = p.chromium.launch()
        page = browser.new_page()
        for path in pages():
            page.goto(f"http://127.0.0.1:{port}{path}")
            chars.update(page.evaluate(js))
        browser.close()
    srv.shutdown()
    return {c for c in chars if not c.isspace() or c == " "}


def unicode_range(codepoints):
    cps = sorted(codepoints)
    ranges, start, prev = [], cps[0], cps[0]
    for cp in cps[1:]:
        if cp == prev + 1:
            prev = cp
            continue
        ranges.append((start, prev))
        start = prev = cp
    ranges.append((start, prev))
    return ", ".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in ranges)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    source = sys.argv[1]
    if not os.path.isdir(DIST):
        sys.exit("Run `npm run build` first.")
    chars = collect_serif_text()
    opts = subset.Options()
    opts.flavor = "woff2"
    opts.layout_features = ["*"]
    opts.name_IDs = ["*"]
    opts.notdef_outline = True
    opts.hinting = False
    opts.desubroutinize = True
    font = subset.load_font(source, opts)
    sub = subset.Subsetter(opts)
    sub.populate(text="".join(chars))
    sub.subset(font)
    cmap = font.getBestCmap()
    covered = {cp for cp in map(ord, chars) if cp in cmap}
    subset.save_font(font, OUT_FONT, opts)
    css = (
        "/* Generated by scripts/subset-serif-font.py. Do not edit by hand. */\n"
        "@font-face {\n"
        '  font-family: "Noto Serif SC Subset";\n'
        "  font-style: normal;\n"
        "  font-weight: 600;\n"
        "  font-display: swap;\n"
        '  src: url(/fonts/noto-serif-sc-subset.woff2) format("woff2");\n'
        f"  unicode-range: {unicode_range(covered)};\n"
        "}\n"
    )
    with open(OUT_CSS, "w", encoding="utf-8") as fh:
        fh.write(css)
    print(f"{len(covered)} characters, {os.path.getsize(OUT_FONT) / 1024:.0f} KB -> {os.path.relpath(OUT_FONT, ROOT)}")


if __name__ == "__main__":
    main()
